"""Canonical MCP tool parameter types and metadata.

The **authoritative** MCP wire schemas are generated by the SDK from the tool
handler signatures in :mod:`qwen_research.mcp.server` (via pydantic). There are
no hand-written JSON-Schema dicts here that could drift from the code: the
parameter *types* used in those signatures are defined once, below, as
``Annotated``/``Literal`` aliases, and the SDK turns them into the wire schema
(``Literal`` → ``enum``, ``Field(description=...)`` → ``description``, the
signature default → ``default``, absence of a default → ``required``).

Tool descriptions and the tool list also live here, because they are the same
metadata the SDK exposes on the wire via ``add_tool(description=...)``.
"""

from __future__ import annotations

from typing import Annotated, Any, Literal

from pydantic import Field

# Enum value sets. These enumerate the domain enum values / profile names as
# string ``Literal``s (so the wire schema carries a simple inline ``enum`` and
# handlers receive plain strings). The values are the *same* values the domain
# enumerates; the tests in ``tests/mcp/test_schemas.py`` assert the resulting
# wire enums match ``OperatingMode`` and ``PROFILES`` exactly, so they cannot
# drift silently.
OperatingModeName = Literal["studio_native", "gateway_inference", "hybrid"]
ReasoningProfileName = Literal["FAST", "NORMAL", "DEEP", "XHIGH", "EXTREME"]

# Parameter types (Annotated[..., Field(description=...)]). Defaults and
# required-ness are declared in the handler signatures, not here.
SessionIdParam = Annotated[str, Field(description="The session identifier.")]
TaskIdParam = Annotated[str, Field(description="The task identifier.")]
DescriptionParam = Annotated[str, Field(description="The task description.")]
ProjectIdParam = Annotated[str, Field(description="The project id for the session.")]
ModeParam = Annotated[OperatingModeName, Field(description="The operating mode.")]
ReasoningProfileParam = Annotated[
    ReasoningProfileName, Field(description="The reasoning profile name.")
]
MetadataParam = Annotated[
    dict[str, str] | None, Field(description="Optional string key/value metadata.")
]
OptionalSessionIdParam = Annotated[
    str | None,
    Field(description="Optional existing session id; a new session is created if omitted."),
]
QueryParam = Annotated[str, Field(description="The search query text.")]
LimitParam = Annotated[int, Field(description="Maximum number of results.", ge=1, le=100)]
RootsParam = Annotated[
    list[str] | None, Field(description="Optional corpus root ids to restrict the search to.")
]
DocumentTypesParam = Annotated[
    list[str] | None,
    Field(description="Optional media types (e.g. 'text/markdown') to filter by."),
]
PathPrefixParam = Annotated[
    str | None, Field(description="Optional relative path prefix to filter by.")
]
DocumentIdParam = Annotated[str, Field(description="The document identifier.")]

# Phase 4 retrieval params.
RetrievalModeName = Literal["lexical", "semantic", "hybrid"]
RetrievalModeParam = Annotated[RetrievalModeName, Field(description="Retrieval mode.")]
LexicalKParam = Annotated[int, Field(description="Lexical candidate count.", ge=1, le=100)]
SemanticKParam = Annotated[int, Field(description="Semantic candidate count.", ge=1, le=100)]
MaxChunksPerDocumentParam = Annotated[
    int, Field(description="Maximum chunks per document (diversity).", ge=1, le=50)
]

# Phase 4 memory params.
OptionalQueryParam = Annotated[str | None, Field(description="Optional query text.")]
ContentParam = Annotated[str, Field(description="The memory content (structured text).")]
StringListParam = Annotated[
    list[str] | None, Field(description="Optional list of reference ids.")
]
StatusParam = Annotated[str | None, Field(description="Optional status value.")]

# Phase 5 evidence-integrity params.
ClaimTypeName = Literal[
    "factual", "causal", "comparative", "quantitative", "definitional",
    "predictive", "methodological", "normative", "unknown",
]
ClaimTypeParam = Annotated[ClaimTypeName, Field(description="The claim type.")]
ClaimIdParam = Annotated[str, Field(description="The claim identifier.")]
EvidenceIdParam = Annotated[str, Field(description="The evidence (chunk) identifier.")]
ReportIdParam = Annotated[str, Field(description="The verification report identifier.")]
ClaimEvidenceRelationshipName = Literal[
    "supports", "contradicts", "qualifies", "contextualizes", "does_not_address",
]
ClaimEvidenceRelationshipParam = Annotated[
    ClaimEvidenceRelationshipName, Field(description="The claim-evidence relationship.")
]
RationaleParam = Annotated[str | None, Field(description="Optional rationale text.")]

# Phase 6 deterministic-computation params.
ComputationOperationName = Literal[
    "calculate", "aggregate", "filter", "join", "describe", "summarize",
    "group", "count", "statistics", "correlation", "regression", "transform",
    "simulate", "custom_python", "custom_sql",
]
ComputationOperationParam = Annotated[
    ComputationOperationName, Field(description="The computation operation.")
]
DatasetRefParam = Annotated[
    dict[str, Any],
    Field(
        description=(
            "A dataset reference with optional keys root_id, relative_path, "
            "document_id, dataset_id, artifact_id, format."
        )
    ),
]
DatasetRefsParam = Annotated[
    list[dict[str, Any]] | None, Field(description="A list of dataset references.")
]
ComputationIdParam = Annotated[str, Field(description="The computation identifier.")]
QuerySqlParam = Annotated[str, Field(description="A single validated SQL query.")]
ParametersParam = Annotated[
    dict[str, Any] | None, Field(description="Optional operation parameters.")
]
PythonSourceParam = Annotated[
    str, Field(description="Python source code to execute in the sandbox.")
]
SeedParam = Annotated[
    int | None, Field(description="Optional seed for deterministic operations.")
]

